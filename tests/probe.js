// roles/probe.js pure parts: safety override + target priority + forbidden-room matrix + spawn gate
const path = require('path'), assert = require('assert');
Object.assign(global, { _: require('lodash'), ATTACK: 'attack', RANGED_ATTACK: 'ranged_attack', HEAL: 'heal', CARRY: 'carry', WORK: 'work', CLAIM: 'claim', MOVE: 'move', RESOURCE_ENERGY: 'energy', BODYPART_COST: { move: 50, work: 100, carry: 50, attack: 80, ranged_attack: 150, heal: 250, claim: 600, tough: 10 } });
const P = require(path.join(__dirname, '..', 'src/roles/probe.js'));
const cr = (parts, x = 10, y = 10, hits = 100) => ({ body: parts.map(type => ({ type, hits: 100 })), pos: { x, y }, hits });
const me = { hits: 1600, hitsMax: 1600, heal: 3 };
assert.strictEqual(P.BODY().reduce((a, p) => a + BODYPART_COST[p], 0), 1800, 'body 1800');
assert.strictEqual(P.BODY().length, 16);
assert.strictEqual(P.danger(me, [cr(['work', 'carry', 'move'])], []), null, 'economy creeps safe');
assert.strictEqual(P.danger(me, [cr(['ranged_attack', 'ranged_attack', 'move'])], []), null, '20 dps < 36 heal');
assert.ok(P.danger(me, [cr(['attack', 'attack', 'move'])], []), '60 dps > 36 heal');
assert.ok(P.danger(me, [cr(Array(14).fill('attack'))], []), '7T14A21M outguns');
assert.ok(P.danger({ hits: 1100, hitsMax: 1600, heal: 3 }, [], []), 'hits<70%');
assert.ok(P.danger(me, [], [{ store: { energy: 500 } }]), 'tower');
assert.strictEqual(P.danger(me, [], [{ store: { energy: 0 } }]), null, 'empty tower ignored');
const t = P.pickTarget({ x: 10, y: 10 }, [cr(['work', 'move'], 11, 10), cr(['carry', 'move'], 12, 10), cr(['claim', 'move'], 10, 11), cr(['heal', 'move'], 20, 20)]);
assert.strictEqual(t.body[0].type, 'heal', 'healer first');
assert.strictEqual(P.pickTarget({ x: 10, y: 10 }, [cr(['work', 'move'], 11, 10), cr(['carry', 'move'], 14, 10)]).body[0].type, 'carry', 'hauler before miner');
const m = { v: {}, set(x, y, c) { this.v[x * 50 + y] = c; }, get(x, y) { return this.v[x * 50 + y] || 0; } };
P.matrixFor('W47N9', m); assert.strictEqual(m.get(25, 25), 255, 'W47N9 forbidden');
const m2 = Object.assign({}, m, { v: {} }); P.matrixFor('W47N8', m2); assert.strictEqual(m2.get(20, 7), 255); assert.strictEqual(m2.get(20, 8), 0, 'y<8 blocked');
for (const [x, y] of P.WAYPOINTS) assert.ok(y >= 8, 'waypoint y>=8');
global.Memory = {}; global.Game = { creeps: {} };
const room = { storage: { store: { energy: 5000 } } };
assert.strictEqual(P.wantSpawn(room), false, 'no flag');
Memory.ops = { probe: { spawn: true } }; assert.strictEqual(P.wantSpawn(room), true);
assert.strictEqual(P.wantSpawn({ storage: { store: { energy: 3000 } } }), false, 'storage<3100');
Game.time = 1; P.noteSpawned('probe1'); assert.strictEqual(P.wantSpawn(room), false, 'once'); assert.strictEqual(Memory.ops.probe.spawn, false);
console.log('probe tests ok');
