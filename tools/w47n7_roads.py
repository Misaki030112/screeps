"""W47N7 remote haul roads (generated -> src/rooms/w47n8/remote_roads.js).
Shortest travel path per W47N7 source container -> W47N8 storage (35,32), Dijkstra road 1 / plain 2 / swamp 10
(= ticks/tile for a loaded 2C:1M rhauler), exit seam crossed straight. W47N8 side reuses the target road net (roads.js +
w8link) and treats planned v3b structures as walls; W47N7 existing roads count as road so surviving segments are reused.
Only the W47N7 tiles are emitted (W47N8 tiles are already in roads.js). Re-run after layout changes."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import model_w8 as M
ROOT = M.ROOT
def js(p): import subprocess; return json.loads(subprocess.check_output(['node', '-e', f"console.log(JSON.stringify(require('{p}')))"], cwd=ROOT))
T, objs, roads, block = M.load()
R8 = js('./src/rooms/w47n8/roads.js'); L = js('./src/rooms/w47n8/layout.js'); LK = js('./src/layouts/w8link.js')
plan_roads = {tuple(p) for p in R8['ROADS'] + LK['W47N8']}
roads = {p for p in roads if p[1] >= 50} | plan_roads
for t, ps in L['ORDER'].items():
    if t not in ('road', 'rampart', 'container'): block |= {tuple(p) for p in ps}
out, info = set(), []
for src, stand in [((17, 17), (18, 17)), ((30, 35), (31, 34))]:
    st = (stand[0], stand[1] + 50)
    path = M.dijkstra(T, roads, block, st, (35, 32), 1)
    rem = [(x, y - 50) for x, y in path if y >= 50 and (x, y) != st]
    out |= set(rem); info.append({'stand': stand, 'len': len(path), 'w47n7': len(rem), 'w47n8_offplan': [p for p in path if p[1] < 50 and p not in plan_roads]})
tiles = sorted(out)
open(os.path.join(ROOT, 'src/rooms/w47n8/remote_roads.js'), 'w').write(
    '// GENERATED by tools/w47n7_roads.py: W47N7 haul roads (source containers -> N exit -> W47N8 storage), shortest travel path.\n'
    '// Placed by w8rminer/w8rhauler when missing and repaired by loaded rhaulers in passing.\n'
    'module.exports = ' + json.dumps({'room': 'W47N7', 'ROADS': [list(p) for p in tiles]}) + ';\n')
print(json.dumps(info)); print(len(tiles), 'W47N7 tiles')
