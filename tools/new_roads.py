"""Plan (1) W47N8 hub -> W46N8 storage link road and (2) W47N8 south corridor road (Misaki 09:18). Writes src/layouts/w8link.js + png."""
import sys, json, heapq
sys.path.insert(0, 'scripts'); sys.path.insert(0, 'tools'); import api; from model import terrain
from PIL import Image, ImageDraw
R = ['W47N8', 'W46N8']; T = {r: terrain(r) for r in R}; OBJ = {}
for r in R: OBJ[r] = api.req('game/room-objects?room=%s&shard=%s' % (r, api.SHARD))['objects']
W = lambda r, x, y: int(T[r][y*50+x]) & 1; SW = lambda r, x, y: int(T[r][y*50+x]) & 2
road = {(o['room'] if 'room' in o else r, o['x'], o['y']) for r in R for o in OBJ[r] if o['type'] == 'road'}
road = set(); block = set()
WALK = ('road', 'container', 'rampart', 'creep', 'energy', 'tombstone', 'ruin', 'powerCreep')
for r in R:
    for o in OBJ[r]:
        if o['type'] == 'road': road.add((r, o['x'], o['y']))
        elif o['type'] == 'constructionSite' and o.get('structureType') in ('road', 'container', 'rampart'): pass
        elif o['type'] not in WALK: block.add((r, o['x'], o['y']))
L = json.loads(open('src/rooms/w47n8/layout.js').read().split('module.exports = ', 1)[1].rstrip().rstrip(';'))
for t, ps in L['ORDER'].items():
    if t not in ('road', 'container', 'rampart', 'extractor'): block |= {('W47N8', x, y) for x, y in ps}
W8T = set(('W47N8', x, y) for x, y in json.loads(open('src/rooms/w47n8/roads.js').read().split('module.exports = ', 1)[1].rstrip().rstrip(';'))['ROADS'])
def cost(n):
    if n in road or n in W8T: return 1
    return 10 if SW(*n) else 2
def nbrs(p):
    r, x, y = p
    for a in (-1, 0, 1):
        for b in (-1, 0, 1):
            if not (a or b): continue
            nx, ny = x+a, y+b
            if 0 <= nx <= 49 and 0 <= ny <= 49: yield (r, nx, ny)
    if r == 'W47N8' and x == 49: yield ('W46N8', 0, y)
    if r == 'W46N8' and x == 0: yield ('W47N8', 49, y)
def path(starts, goal_fn):
    D = {s: 0 for s in starts}; pq = [(0, s) for s in starts]; prev = {}
    while pq:
        d, p = heapq.heappop(pq)
        if goal_fn(p): break
        if d > D[p]: continue
        for n in nbrs(p):
            if W(*n) or n in block: continue
            nd = d + cost(n)
            if nd < D.get(n, 1e9): D[n] = nd; prev[n] = p; heapq.heappush(pq, (nd, n))
    out = []
    while p in prev: out.append(p); p = prev[p]
    return out[::-1]
st = [o for o in OBJ['W46N8'] if o['type'] == 'storage'][0]
link = path([('W47N8', 33, 33)], lambda p: p[0] == 'W46N8' and max(abs(p[1]-st['x']), abs(p[2]-st['y'])) <= 1)
south = path([('W47N8', 28, 35)], lambda p: p[0] == 'W47N8' and p[2] == 49 and 26 <= p[1] <= 36)
new = lambda P: [p for p in P if p not in road and p not in W8T and 0 < p[1] < 49 and 0 < p[2] < 49]
info = {'link_len': len(link), 'link_tiles': {r: sum(1 for p in link if p[0] == r) for r in R}, 'link_new': {r: sum(1 for p in new(link) if p[0] == r) for r in R},
        'link_swamp_new': sum(1 for p in new(link) if SW(*p)), 'south_len': len(south), 'south_new': len(new(south)), 'south_swamp_new': sum(1 for p in new(south) if SW(*p)),
        'south': [p[1:] for p in south], 'storage': [st['x'], st['y']]}
nl = new(link) + new(south)
info['build_energy'] = sum(1500 if SW(*p) else 300 for p in nl)
info['repair_e_per_tick'] = round(sum(0.005 if SW(*p) else 0.001 for p in nl), 3)
print(json.dumps(info))
out = {'W47N8': [list(p[1:]) for p in link + south if p[0] == 'W47N8' and 0 < p[1] < 49 and 0 < p[2] < 49],
       'W46N8': [list(p[1:]) for p in link if p[0] == 'W46N8' and 0 < p[1] < 49 and 0 < p[2] < 49]}
if len(sys.argv) > 1:
    open('src/layouts/w8link.js', 'w').write('// GENERATED by tools/new_roads.py (Misaki 09:18): W47N8 hub 33,33 <-> W46N8 storage link road + W47N8 south corridor\n'
        '// road. Infrastructure only: no creep crosses rooms because of it.\nmodule.exports = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    S = 9; im = Image.new('RGB', (100*S, 50*S+30), 'white'); d = ImageDraw.Draw(im)
    for i, r in enumerate(R):
        for y in range(50):
            for x in range(50):
                c = (40, 40, 40) if W(r, x, y) else ((150, 170, 120) if SW(r, x, y) else (225, 225, 215))
                if (r, x, y) in road: c = (150, 150, 150)
                if (r, x, y) in block and not W(r, x, y): c = (230, 180, 60)
                d.rectangle([i*50*S+x*S, y*S, i*50*S+x*S+S-1, y*S+S-1], fill=c)
    for P, col in ((link, (0, 90, 255)), (south, (230, 0, 0))):
        for r, x, y in P:
            i = R.index(r); w = 3 if (r, x, y) in road or (r, x, y) in W8T else 1
            d.rectangle([i*50*S+x*S+1, y*S+1, i*50*S+x*S+S-2, y*S+S-2], outline=col, width=2)
    d.line([50*S, 0, 50*S, 50*S], fill='black')
    d.text((4, 50*S+4), 'left W47N8 | right W46N8. blue = hub->storage link road, red = south corridor road. grey=existing road, gold=structures', fill='black')
    d.text((4, 50*S+16), json.dumps({k: v for k, v in info.items() if k != 'south'}), fill='black')
    im.save('/workspace/new_roads.png')
